/// The Makefile of an exported stack. `>` at line start marks a recipe line.
pub fn render_makefile(services: &[String]) -> String {
    let order = startup_queue(services).join(" ");
    let body: String = MAKEFILE
        .lines()
        .map(|l| {
            l.strip_prefix('>')
                .map_or_else(|| l.to_string(), |r| format!("\t{r}"))
        })
        .collect::<Vec<_>>()
        .join("\n");
    format!("# Startup order: {order}\n{body}\n")
}

/// README for the exported tree: quick start plus services grouped by category.
pub fn render_readme(name: &str, services: &[String], catalog: &Catalog) -> String {
    let mut lines = vec![
        format!("# {name}"),
        String::new(),
        "Packaged Docker Shared Services stack generated by `make package`.".into(),
        String::new(),
        "## Quick start".into(),
        String::new(),
        "```bash".into(),
        "make setup   # networks, .env files, shared password, secrets".into(),
        "make up      # validate compose, then start every service in dependency order".into(),
        "make down    # stop and remove containers (volumes are kept)".into(),
        "```".into(),
        String::new(),
        "The first command builds the `dss` binary with cargo. Run `make help` for every command."
            .into(),
        String::new(),
        "## Services".into(),
    ];
    for category in CATEGORIES {
        let members: Vec<&String> = services
            .iter()
            .filter(|s| catalog.get(*s).is_some_and(|e| e.category == *category))
            .collect();
        if members.is_empty() {
            continue;
        }
        lines.extend([String::new(), format!("### {category}"), String::new()]);
        for service in members {
            let entry = &catalog[service];
            lines.push(format!("- **{service}**: {}", entry.description));
            lines.push(format!("  - Containers: {}", entry.containers.join(", ")));
            let ui = if entry.web_ui.is_empty() {
                "none".to_string()
            } else {
                entry.web_ui.join(", ")
            };
            lines.push(format!("  - Web UI: {ui}"));
        }
    }
    lines.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog::{parse_catalog, DEFAULT_DOMAIN};

    fn names(items: &[&str]) -> Vec<String> {
        items.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn makefile_uses_tabs_and_lists_startup_order() {
        let text = render_makefile(&names(&["hindsight", "pgvector", "traefik"]));
        assert!(text.starts_with("# Startup order: traefik pgvector hindsight\n"));
        assert!(text.contains("\n\t@$(DSS) up --all\n"));
        assert!(!text.lines().any(|l| l.starts_with('>')));
    }

    #[test]
    fn readme_groups_selected_services_by_category() {
        let catalog =
            parse_catalog(include_str!("../../service_catalog.json"), DEFAULT_DOMAIN).unwrap();
        let text = render_readme("demo", &names(&["redis", "adminer"]), &catalog);
        assert!(text.starts_with("# demo\n"));
        assert!(text.contains("### Admin UI") && text.contains("- **adminer**"));
        assert!(!text.contains("postgres"));
    }
}
